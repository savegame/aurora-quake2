/*
 * vr_head.h -- ориентация головы по сенсорам для картонного VR (ОС Аврора).
 *
 * Этапы 1-2 плана research/vr_sensors.md §9: чтение акселерометра и
 * гироскопа через sensorfwd, калибровка и фильтр Махони на кватернионах.
 * Камерой модуль НЕ управляет — cl.viewangles не трогается вовсе; это
 * этап 3. Пока наблюдаемый результат — отладочный вывод и калибровка,
 * чтобы гироскоп можно было настроить на устройстве, не ломая управление.
 *
 * Активно только при сборке с -DAURORA_VR=ON (дефайн AURORA_VR и
 * найденный dbus-1); иначе весь модуль — no-op заглушки, движок работает
 * ровно как без него (образец: aurora_keepalive.c, maliit_client.c).
 *
 * Типы в сигнатурах намеренно голые float[3], а не vec3_t: заголовок
 * включается и из backends/sdl, и из refresh, и не должен тащить за
 * собой shared.h.
 */

#ifndef client_vr_head_h
#define client_vr_head_h

#include <stdbool.h>

/* Регистрация cvar'ов и команд. Сенсоры здесь НЕ открываются: создание
   клиента делает один синхронный dbus_bus_get(), и платить за него в
   сборке, где VR никому не нужен, незачем. Вызов из CL_Init. */
void VR_Init( void );

/* Освобождение сессий sensorfwd. Вызов из CL_Shutdown. */
void VR_Shutdown( void );

/* Раз в кадр: двигает автоматы обоих сенсоров, разбирает ВСЕ накопившиеся
   семплы и обновляет ориентацию. Никогда не блокирует. Вызов в начале
   IN_Move — там же, где движок собирает остальной ввод. */
void VR_Frame( void );

/* Идут ли сейчас данные (оба автомата в STREAMING). */
bool VR_Active( void );

/* Углы головы в соглашении Quake 2 (PITCH/YAW/ROLL, градусы), с учётом
   рецентра. Потребителя пока нет — это вход для этапа 3. */
void VR_GetHeadAngles( float angles[3] );

/* Отладочный оверлей поверх кадра при vr_debug != 0. Вызов из
   SCR_UpdateScreen внутри цикла глаз (рисует в 2D-вьюпорте глаза). */
void VR_DrawDebug( void );

#endif /* client_vr_head_h */
