/*
 * vr_head.h -- ориентация головы по сенсорам для картонного VR (ОС Аврора).
 *
 * Этапы 1-3 плана research/vr_sensors.md §9: чтение акселерометра и
 * гироскопа через sensorfwd, калибровка, фильтр Махони на кватернионах
 * и управление камерой головой.
 *
 * Режим включается одним cvar'ом vr_mode (0/1): стерео-сплит gl_stereo 2
 * + сенсоры + голова в cl.viewangles. Выключение возвращает gl_stereo к
 * значению, которое было до включения. vr_enabled остаётся отдельным
 * гейтом «только сенсоры» — для калибровки без стерео и без камеры.
 *
 * Активно только при сборке с -DAURORA_VR=ON (дефайн AURORA_VR и
 * найденный dbus-1); иначе весь модуль — no-op заглушки, движок работает
 * ровно как без него (образец: aurora_keepalive.c, maliit_client.c).
 *
 * Типы в сигнатурах намеренно голые float[3], а не vec3_t: заголовок
 * включается и из backends/sdl, и из refresh, и не должен тащить за
 * собой shared.h.
 */

#ifndef client_vr_head_h
#define client_vr_head_h

#include <stdbool.h>

/* Регистрация cvar'ов и команд. Сенсоры здесь открываются, только если
   vr_enabled или vr_mode уже стоят (конфиг, командная строка, лаунчер):
   создание клиента делает один синхронный dbus_bus_get(), и платить за
   него, когда VR никому не нужен, незачем. Вызов из CL_Init. */
void VR_Init( void );

/* Освобождение сессий sensorfwd. Вызов из CL_Shutdown. */
void VR_Shutdown( void );

/* Раз в кадр: применяет переключение vr_mode, двигает автоматы обоих
   сенсоров, разбирает ВСЕ накопившиеся семплы и обновляет ориентацию.
   Никогда не блокирует. Вызов в начале IN_Move — там же, где движок
   собирает остальной ввод. */
void VR_Frame( void );

/* Идут ли сейчас данные (оба автомата в STREAMING). */
bool VR_Active( void );

/* Включён ли VR-режим (vr_mode применён). Не зависит от того, идут ли
   данные: стерео, скрытый тач-оверлей и гашение kick_angles нужны в
   шлеме и тогда, когда сенсор ещё не открылся. */
bool VR_ModeEnabled( void );

/* Углы головы в соглашении Quake 2 (PITCH/YAW/ROLL, градусы), с учётом
   рецентра и текущего поворота контента. */
void VR_GetHeadAngles( float angles[3] );

/* Голова -> cl.viewangles. Вызов в конце IN_Move, после мыши, стиков и
   тача: yaw головы прибавляется к ним дельтой, pitch и roll выставляются
   абсолютно. В меню, консоли и без данных сенсоров ничего не делает. */
void VR_ApplyHeadToView( void );

/* Фильтр wl_output_transform для R_AuroraUpdateTransform. В VR-режиме
   фиксирует выбор внутри пары (0/2 или 1/3): композитор не должен
   переворачивать картинку в шлеме при сильном наклоне головы. Смена
   пары (другой дисплей, другой тип панели) пропускается без изменений. */
int VR_LockTransform( int transform );

/* Отладочный оверлей поверх кадра при vr_debug != 0. Вызов из
   SCR_UpdateScreen внутри цикла глаз (рисует в 2D-вьюпорте глаза). */
void VR_DrawDebug( void );

/* --- Положение изображений глаз под линзы (vr_lens.c) ------------------
 *
 * Cvar'ы vr_lens_sep_mm / vr_lens_vofs_mm / vr_lens_tilt_mm (мм экрана,
 * архивные) и интерактивная калибровка с геймпада: вход долгим нажатием Y
 * или командой vr_lens_calibrate. Раскладка уходит в RFBO_SetLensLayout
 * только при изменении. */

/* Регистрация cvar'ов и команды. Вызов из VR_Init. */
/* Подмешивает калибровку линз из общего launcher.conf. Вызывается из
   Qcommon_Init сразу после exec user.cfg: значения ставятся в командный
   буфер и перекрывают конфиг текущего мода, а +set из командной строки
   выполняется позже и остаётся главнее. */
void VR_LensLoadShared( void );
void VR_LensInit( void );
void VR_LensShutdown( void );

/* Раз в кадр из IN_Update: долгое нажатие Y, автоповтор шага при
   удержании, передача изменившейся раскладки в FBO-модуль. */
void VR_LensFrame( void );

/* Перехват клавиш в начале Key_Event. true — событие съедено калибровкой.
   Отпускания не съедаются никогда: иначе кнопка, зажатая до входа
   (например +attack), осталась бы нажатой навсегда. */
bool VR_LensKeyEvent( int key, bool down );

/* Идёт ли калибровка (ввод игрока и голова камерой не управляют). */
bool VR_LensCalibrating( void );

/* Мишень и подсказка. Вызов из SCR_UpdateScreen в конце прохода глаза. */
void VR_LensDraw( void );

#endif /* client_vr_head_h */
